import time
import numpy as np
import tensorflow as tf
from tensorflow.keras import layers, models
from sklearn.neighbors import KNeighborsClassifier
from sklearn.svm import SVC
from sklearn.metrics import accuracy_score

# ── 1. Chargement et prétraitement MNIST ───────────────────────────────────────
print("Chargement des données MNIST...")
(x_train, y_train), (x_test, y_test) = tf.keras.datasets.mnist.load_data()

# Pour k-NN et SVM : aplatir les images en vecteurs 784
x_train_flat = x_train.reshape(60000, -1).astype('float32') / 255
x_test_flat  = x_test.reshape(10000, -1).astype('float32') / 255

# Pour CNN : garder la forme 28x28x1
x_train_cnn = x_train.reshape(60000, 28, 28, 1).astype('float32') / 255
x_test_cnn  = x_test.reshape(10000, 28, 28, 1).astype('float32') / 255

# On utilise un sous-ensemble pour k-NN et SVM (trop lents sur 60 000 exemples)
N_TRAIN = 10000  # augmente si tu as le temps (max 60000)
N_TEST  = 2000

x_tr = x_train_flat[:N_TRAIN]
y_tr = y_train[:N_TRAIN]
x_te = x_test_flat[:N_TEST]
y_te = y_test[:N_TEST]

resultats = {}  # stocke les résultats pour le tableau final

# ── 2. k-NN ───────────────────────────────────────────────────────────────────
print("\n--- k-NN (k=3) ---")
t0 = time.time()
knn = KNeighborsClassifier(n_neighbors=3, n_jobs=-1)
knn.fit(x_tr, y_tr)
t_train_knn = time.time() - t0

t0 = time.time()
y_pred_knn = knn.predict(x_te)
t_test_knn = time.time() - t0

acc_knn = accuracy_score(y_te, y_pred_knn)
print(f"Précision : {acc_knn*100:.2f}%")
print(f"Temps entraînement : {t_train_knn:.2f}s | Temps inférence : {t_test_knn:.2f}s")
resultats['k-NN (k=3)'] = {
    'précision': f"{acc_knn*100:.2f}%",
    'temps_train': f"{t_train_knn:.2f}s",
    'temps_test': f"{t_test_knn:.2f}s",
    'données': f"{N_TRAIN} train / {N_TEST} test"
}

# ── 3. SVM ────────────────────────────────────────────────────────────────────
print("\n--- SVM (noyau RBF) ---")
t0 = time.time()
svm = SVC(kernel='rbf', C=5, gamma='scale')
svm.fit(x_tr, y_tr)
t_train_svm = time.time() - t0

t0 = time.time()
y_pred_svm = svm.predict(x_te)
t_test_svm = time.time() - t0

acc_svm = accuracy_score(y_te, y_pred_svm)
print(f"Précision : {acc_svm*100:.2f}%")
print(f"Temps entraînement : {t_train_svm:.2f}s | Temps inférence : {t_test_svm:.2f}s")
resultats['SVM (RBF)'] = {
    'précision': f"{acc_svm*100:.2f}%",
    'temps_train': f"{t_train_svm:.2f}s",
    'temps_test': f"{t_test_svm:.2f}s",
    'données': f"{N_TRAIN} train / {N_TEST} test"
}

# ── 4. CNN ────────────────────────────────────────────────────────────────────
print("\n--- CNN ---")
cnn = models.Sequential([
    layers.Conv2D(32, (3, 3), activation='relu', input_shape=(28, 28, 1)),
    layers.MaxPooling2D((2, 2)),
    layers.Conv2D(64, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),
    layers.Flatten(),
    layers.Dense(64, activation='relu'),
    layers.Dense(10, activation='softmax')
])
cnn.compile(optimizer='adam',
            loss='sparse_categorical_crossentropy',
            metrics=['accuracy'])

t0 = time.time()
cnn.fit(x_train_cnn, y_train, epochs=5, batch_size=64,
        validation_split=0.1, verbose=1)
t_train_cnn = time.time() - t0

t0 = time.time()
test_loss, acc_cnn = cnn.evaluate(x_test_cnn, y_test, verbose=0)
t_test_cnn = time.time() - t0

print(f"Précision : {acc_cnn*100:.2f}%")
print(f"Temps entraînement : {t_train_cnn:.2f}s | Temps inférence : {t_test_cnn:.2f}s")
resultats['CNN'] = {
    'précision': f"{acc_cnn*100:.2f}%",
    'temps_train': f"{t_train_cnn:.2f}s",
    'temps_test': f"{t_test_cnn:.2f}s",
    'données': "60000 train / 10000 test"
}

# ── 5. Tableau récapitulatif ───────────────────────────────────────────────────
print("\n" + "="*65)
print(f"{'Algorithme':<15} {'Précision':>12} {'T. train':>12} {'T. test':>12}")
print("="*65)
for algo, res in resultats.items():
    print(f"{algo:<15} {res['précision']:>12} {res['temps_train']:>12} {res['temps_test']:>12}")
print("="*65)
print("\nNote : k-NN et SVM ont été évalués sur un sous-ensemble de")
print(f"{N_TRAIN} images d'entraînement et {N_TEST} images de test.")
print("Le CNN a été entraîné sur la totalité des 60 000 images.")

# Sauvegarde du modèle CNN
cnn.save('modele_cnn_mnist.h5')
print("\nModèle CNN sauvegardé : modele_cnn_mnist.h5")


"""
predire_plusieurs_chiffres.py
-----------------------------
Détecte et prédit automatiquement plusieurs chiffres sur une même image.
Fonctionne avec des images style MNIST (fond noir, chiffres blancs)
ou des photos réelles (fond blanc, chiffres noirs).

À exécuter sur Google Colab.
"""

import numpy as np
import cv2
import tensorflow as tf
import matplotlib.pyplot as plt
import matplotlib.patches as patches
from google.colab import files

# ── 1. Charger le modèle ───────────────────────────────────────────────────────
print("Chargement du modèle CNN...")
model = tf.keras.models.load_model('modele_cnn_mnist.h5')
print("Modèle chargé !\n")

# ── 2. Uploader l'image ────────────────────────────────────────────────────────
print("Uploade ton image contenant les chiffres...")
uploaded = files.upload()
nom_fichier = list(uploaded.keys())[0]

# ── 3. Chargement et détection du type d'image ────────────────────────────────
img_originale = cv2.imread(nom_fichier)
img_originale_rgb = cv2.cvtColor(img_originale, cv2.COLOR_BGR2RGB)
img_gris = cv2.cvtColor(img_originale, cv2.COLOR_BGR2GRAY)

# Détection automatique : fond noir ou fond blanc ?
# Si la majorité des pixels est sombre → style MNIST (fond noir)
# Sinon → photo réelle (fond blanc)
moyenne = np.mean(img_gris)
fond_noir = moyenne < 127

if fond_noir:
    print("Image style MNIST détectée (fond noir, chiffres blancs)")
    img_binaire = cv2.threshold(img_gris, 50, 255, cv2.THRESH_BINARY)[1]
else:
    print("Photo réelle détectée (fond blanc, chiffres noirs)")
    img_binaire = cv2.adaptiveThreshold(
        img_gris, 255,
        cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
        cv2.THRESH_BINARY_INV,
        blockSize=51, C=10
    )
    # Épaissir les traits fins
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (3, 3))
    img_binaire = cv2.dilate(img_binaire, kernel, iterations=2)

# ── 4. Détection des contours de chaque chiffre ───────────────────────────────
contours, _ = cv2.findContours(img_binaire, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

# Filtrer les petits contours (bruit)
hauteur_img = img_binaire.shape[0]
contours_filtres = []
for cnt in contours:
    x, y, w, h = cv2.boundingRect(cnt)
    # Garder seulement les contours assez grands
    if h > hauteur_img * 0.2 and w > 5:
        contours_filtres.append((x, y, w, h))

# Trier de gauche à droite
contours_filtres = sorted(contours_filtres, key=lambda c: c[0])

print(f"\n{len(contours_filtres)} chiffre(s) détecté(s) !")

# ── 5. Prédiction pour chaque chiffre ─────────────────────────────────────────
resultats = []

for i, (x, y, w, h) in enumerate(contours_filtres):
    # Ajouter une marge autour du chiffre
    padding = int(max(w, h) * 0.2)
    x1 = max(0, x - padding)
    y1 = max(0, y - padding)
    x2 = min(img_binaire.shape[1], x + w + padding)
    y2 = min(img_binaire.shape[0], y + h + padding)

    # Extraire le chiffre
    chiffre_crop = img_binaire[y1:y2, x1:x2]

    # Rendre le crop carré
    ch, cw = chiffre_crop.shape
    taille = max(ch, cw)
    img_carree = np.zeros((taille, taille), dtype=np.uint8)
    offset_y = (taille - ch) // 2
    offset_x = (taille - cw) // 2
    img_carree[offset_y:offset_y+ch, offset_x:offset_x+cw] = chiffre_crop

    # Redimensionner en 28x28
    img_28 = cv2.resize(img_carree, (28, 28), interpolation=cv2.INTER_AREA)

    # Normaliser et prédire
    img_norm = img_28.astype('float32') / 255
    img_input = img_norm.reshape(1, 28, 28, 1)
    prediction = model.predict(img_input, verbose=0)
    chiffre_predit = np.argmax(prediction)
    confiance = np.max(prediction) * 100

    resultats.append({
        'position': (x1, y1, x2, y2),
        'chiffre': chiffre_predit,
        'confiance': confiance,
        'img_28': img_28,
        'prediction': prediction[0]
    })

# ── 6. Affichage des résultats ─────────────────────────────────────────────────
n = len(resultats)

# Figure 1 : image annotée avec les prédictions
fig1, ax = plt.subplots(1, 1, figsize=(14, 5))
ax.imshow(img_originale_rgb)
for r in resultats:
    x1, y1, x2, y2 = r['position']
    couleur = '#2ecc71' if r['confiance'] > 80 else '#e67e22' if r['confiance'] > 50 else '#e74c3c'
    rect = patches.Rectangle((x1, y1), x2-x1, y2-y1,
                               linewidth=2, edgecolor=couleur, facecolor='none')
    ax.add_patch(rect)
    ax.text(x1, y1 - 8, f"{r['chiffre']} ({r['confiance']:.0f}%)",
            color=couleur, fontsize=12, fontweight='bold',
            bbox=dict(boxstyle='round,pad=0.2', facecolor='black', alpha=0.6))
ax.set_title("Détection et reconnaissance des chiffres", fontsize=14, fontweight='bold')
ax.axis('off')
plt.tight_layout()
plt.savefig('detection_multiple.png', bbox_inches='tight', dpi=150)
plt.show()

# Figure 2 : détail de chaque chiffre
if n > 0:
    fig2, axes = plt.subplots(2, n, figsize=(n * 2, 5))
    if n == 1:
        axes = np.array([[axes[0]], [axes[1]]])

    for i, r in enumerate(resultats):
        # Ligne 1 : image 28x28
        axes[0][i].imshow(r['img_28'], cmap='gray')
        axes[0][i].set_title(f"Prédit : {r['chiffre']}\n{r['confiance']:.1f}%",
                              fontsize=10, fontweight='bold')
        axes[0][i].axis('off')

        # Ligne 2 : top 3 probabilités
        top3 = np.argsort(r['prediction'])[::-1][:3]
        couleurs_bar = ['#2ecc71', '#3498db', '#95a5a6']
        axes[1][i].barh([str(top3[j]) for j in range(3)],
                        [r['prediction'][top3[j]] * 100 for j in range(3)],
                        color=couleurs_bar)
        axes[1][i].set_xlim(0, 110)
        axes[1][i].tick_params(labelsize=9)

    fig2.suptitle("Détail par chiffre (image 28×28 + top 3 probabilités)",
                  fontsize=13, fontweight='bold')
    plt.tight_layout()
    plt.savefig('detail_chiffres.png', bbox_inches='tight', dpi=150)
    plt.show()

# ── 7. Résumé textuel ─────────────────────────────────────────────────────────
print("\n" + "="*50)
print("  RÉSULTATS DE LA RECONNAISSANCE")
print("="*50)
sequence = ""
for i, r in enumerate(resultats):
    statut = "✓" if r['confiance'] > 80 else "~" if r['confiance'] > 50 else "✗"
    print(f"  Chiffre {i+1} : {r['chiffre']}  ({r['confiance']:.1f}%)  {statut}")
    sequence += str(r['chiffre'])
print(f"\n  Séquence lue : {' '.join(sequence)}")
print("="*50)
print("\n✓ = confiance > 80%  |  ~ = confiance 50-80%  |  ✗ = confiance < 50%")
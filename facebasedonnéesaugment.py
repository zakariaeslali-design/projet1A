def augment_face(face_img):
    """
    Génère des variantes d'un visage déjà cropé et redimensionné (160x160, RGB).
    Retourne une liste d'images numpy (inclut l'original).
    """
    augmented = [face_img]
    pil_img = Image.fromarray(face_img)

    # 1. Flip horizontal
    augmented.append(cv.flip(face_img, 1))

    # 2. Rotations légères
    h, w = face_img.shape[:2]
    center = (w // 2, h // 2)
    for angle in [-15, -8, 8, 15]:
        M = cv.getRotationMatrix2D(center, angle, 1.0)
        rotated = cv.warpAffine(face_img, M, (w, h),
                                borderMode=cv.BORDER_REFLECT)
        augmented.append(rotated)

    # 3. Variations de luminosité
    for factor in [0.6, 0.8, 1.2, 1.4]:
        bright = np.array(ImageEnhance.Brightness(pil_img).enhance(factor))
        augmented.append(bright)

    # 4. Variations de contraste
    for factor in [0.75, 1.25]:
        contrast = np.array(ImageEnhance.Contrast(pil_img).enhance(factor))
        augmented.append(contrast)

    # 5. Légère translation (±8px)
    for dx, dy in [(-8, 0), (8, 0), (0, -8), (0, 8)]:
        M_t = np.float32([[1, 0, dx], [0, 1, dy]])
        shifted = cv.warpAffine(face_img, M_t, (w, h),
                                borderMode=cv.BORDER_REFLECT)
        augmented.append(shifted)

    # Total : 1 + 1 + 4 + 4 + 2 + 4 = 16 variantes par photo
    return augmented


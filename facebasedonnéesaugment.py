class FACELOADING:
    def __init__(self, directory, augment=True):
        self.directory   = directory
        self.target_size = (160, 160)
        self.augment     = augment
        self.X = []
        self.Y = []
        self.detector = MTCNN()

    def extract_face(self, filename):
        img = cv.imread(filename)
        img = cv.cvtColor(img, cv.COLOR_BGR2RGB)
        results = self.detector.detect_faces(img)
        if not results:
            raise ValueError(f"Aucun visage détecté dans {filename}")
        x, y, w, h = results[0]['box']
        x, y = abs(x), abs(y)
        face = img[y:y+h, x:x+w]
        face_arr = cv.resize(face, self.target_size)
        return face_arr

    def load_faces(self, dir):
        FACES = []
        for im_name in os.listdir(dir):
            try:
                path = dir + im_name
                face = self.extract_face(path)

                if self.augment:
                    variants = augment_face(face)
                    FACES.extend(variants)
                else:
                    FACES.append(face)

            except Exception as e:
                print(f"  ⚠ Ignoré ({im_name}) : {e}")
        return FACES

    def load_classes(self):
        for sub_dir in os.listdir(self.directory):
            path = self.directory + '/' + sub_dir + '/'
            FACES = self.load_faces(path)
            labels = [sub_dir for _ in range(len(FACES))]
            print(f"✅ {sub_dir} : {len(labels)} images (avec augmentation)")
            self.X.extend(FACES)
            self.Y.extend(labels)

        return np.asarray(self.X), np.asarray(self.Y)

    def plot_images(self):
        plt.figure(figsize=(16, 12))
        for num, image in enumerate(self.X):
            ncols = 6
            nrows = len(self.Y) // ncols + 1
            plt.subplot(nrows, ncols, num + 1)
            plt.imshow(image)
            plt.axis('off')

